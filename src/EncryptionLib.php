<?php

/*
 * Library just for cryptography. E.g. encryption, and password hashing.
 */

namespace Programster\CoreLibs;


use Programster\CoreLibs\Exceptions\DecryptionFailedException;
use Programster\CoreLibs\Exceptions\MissingExtensionException;
use Programster\CoreLibs\Exceptions\BadArgumentException;

final class EncryptionLib
{
    # The first byte of everything encrypt() produces, identifying the format it is in. If the algorithm ever needs to
    # change, a new version can be added, and decrypt() can still decrypt data in the older formats.
    private const FORMAT_VERSION_SECRETBOX = 1;


    /**
     * Generate a new random key, suitable for encrypt() and decrypt().
     * The key is raw binary, so to store it (e.g. in a config file or environment variable), base64_encode() it, and
     * then base64_decode() it again when loading it.
     * WARNING - keep this key secret, and don't lose it, as anything encrypted with it can't be decrypted without it.
     * @return string - a random 32-byte key.
     */
    public static function generateKey(): string
    {
        return sodium_crypto_secretbox_keygen();
    }


    /**
     * Encrypt a string, using authenticated encryption (libsodium's secretbox: XSalsa20-Poly1305). As well as keeping
     * the content secret, this means that if the encrypted text is tampered with, decrypt() will refuse to decrypt it.
     * A random nonce is generated for every call and stored in the output, so encrypting the same text twice gives
     * different results.
     * @param string $plaintext - the text to encrypt.
     * @param string $key - the key to encrypt with, as generated by generateKey(). Must be exactly 32 bytes.
     * @return string - the encrypted text, as base64. This is safe to store in a database, JSON, config files etc.
     * @throws BadArgumentException - if the key is not exactly 32 bytes.
     */
    public static function encrypt(#[\SensitiveParameter] string $plaintext, #[\SensitiveParameter] string $key): string
    {
        self::validateKey($key);

        $nonce = random_bytes(SODIUM_CRYPTO_SECRETBOX_NONCEBYTES);
        $ciphertext = sodium_crypto_secretbox($plaintext, $nonce, $key);

        # Format: [1 byte version][24 byte nonce][ciphertext, including its 16 byte authentication tag]
        $encrypted = base64_encode(chr(self::FORMAT_VERSION_SECRETBOX) . $nonce . $ciphertext);
        return $encrypted;
    }


    /**
     * Decrypt a string that was encrypted with encrypt().
     * @param string $encrypted - the encrypted text, as returned by encrypt().
     * @param string $key - the key it was encrypted with. Must be exactly 32 bytes.
     * @return string - the decrypted text.
     * @throws DecryptionFailedException - if the text could not be decrypted, because the key is wrong, the encrypted
     *                                     text has been tampered with or damaged, or it is not something encrypt()
     *                                     produced.
     * @throws BadArgumentException - if the key is not exactly 32 bytes.
     */
    public static function decrypt(string $encrypted, #[\SensitiveParameter] string $key): string
    {
        self::validateKey($key);

        $decoded = base64_decode($encrypted, true);
        $minimumLength = 1 + SODIUM_CRYPTO_SECRETBOX_NONCEBYTES + SODIUM_CRYPTO_SECRETBOX_MACBYTES;

        if ($decoded === false || strlen($decoded) < $minimumLength)
        {
            throw new DecryptionFailedException("The encrypted text is not in the format that encrypt() produces.");
        }

        $version = ord($decoded[0]);

        if ($version !== self::FORMAT_VERSION_SECRETBOX)
        {
            throw new DecryptionFailedException("The encrypted text is in an unknown format (version {$version}).");
        }

        $nonce = substr($decoded, 1, SODIUM_CRYPTO_SECRETBOX_NONCEBYTES);
        $ciphertext = substr($decoded, 1 + SODIUM_CRYPTO_SECRETBOX_NONCEBYTES);
        $plaintext = sodium_crypto_secretbox_open($ciphertext, $nonce, $key);

        if ($plaintext === false)
        {
            throw new DecryptionFailedException(
                "Failed to decrypt the text. Either the key is wrong, or the encrypted text has been tampered with " .
                "or damaged."
            );
        }

        return $plaintext;
    }


    /**
     * Decrypt a string that was encrypted with the encrypt() method from version 2 of this library (AES-256-OFB).
     * This is only provided so that existing data can be decrypted and then re-encrypted with encrypt(), as the old
     * format has no protection against tampering.
     * WARNING - unlike decrypt(), the old format can't detect a wrong key: decrypting with the wrong key or IV returns
     * garbage rather than throwing an exception.
     * @param string $encryptedText - the encrypted text, as returned by the old encrypt() method.
     * @param string $key - the key it was encrypted with.
     * @param string $initializationVector - the 16 byte initialization vector it was encrypted with.
     * @return string - the decrypted text.
     * @throws DecryptionFailedException - if OpenSSL could not decrypt the text (e.g. it is not valid base64).
     * @throws MissingExtensionException - if the openssl extension isn't available.
     */
    public static function decryptLegacy(
        string $encryptedText,
        #[\SensitiveParameter] string $key,
        string $initializationVector
    ): string
    {
        if (!extension_loaded('openssl'))
        {
            throw new MissingExtensionException("Your PHP does not have the openssl extension.");
        }

        # The old encrypt() returned base64. OpenSSL quietly treats invalid base64 as empty, so check it ourselves.
        if (base64_decode($encryptedText, true) === false)
        {
            throw new DecryptionFailedException(
                "The encrypted text is not valid base64, so cannot be legacy encrypted text."
            );
        }

        # These must stay exactly as the old encrypt() method used them, or old data won't decrypt correctly.
        $plaintext = @openssl_decrypt(
            $encryptedText,
            "AES-256-OFB",
            $key,
            OPENSSL_ZERO_PADDING,
            $initializationVector
        );

        if ($plaintext === false)
        {
            throw new DecryptionFailedException("Failed to decrypt the text using the legacy (version 2) format.");
        }

        return $plaintext;
    }


    /**
     * Converts a raw password into a password hash
     * @param string $rawPassword - the password we wish to hash
     * @return string - the generated hash
     */
    public static function generatePasswordHash(#[\SensitiveParameter] string $rawPassword): string
    {
        return password_hash($rawPassword, PASSWORD_DEFAULT);
    }


    /**
     * Counterpart to generatePasswordHash. This function should be used to
     * verify that the provided password is correct. This just wraps around
     * password_verify which automatically knows which algo and cost
     * to use as they are buried in the hash.
     * @param string $rawPassword - the raw password that the user entered.
     * @param string $expectedHash - the hash that we are expecting
     *                              (generated from generatePasswordHash)
     * @return bool - true if valid, false if not.
     */
    public static function verifyPassword(#[\SensitiveParameter] string $rawPassword, string $expectedHash): bool
    {
        return password_verify($rawPassword, $expectedHash);
    }


    /**
     * Check that a key is the right length for encrypt() and decrypt().
     * @param string $key - the key to check.
     * @return void
     * @throws BadArgumentException - if the key is not exactly 32 bytes.
     */
    private static function validateKey(#[\SensitiveParameter] string $key): void
    {
        if (strlen($key) !== SODIUM_CRYPTO_SECRETBOX_KEYBYTES)
        {
            throw new BadArgumentException(
                "The key must be exactly " . SODIUM_CRYPTO_SECRETBOX_KEYBYTES . " bytes, but is " . strlen($key) .
                " bytes. Please use EncryptionLib::generateKey() to create one. If you are loading a stored key, make" .
                " sure you have base64_decode()d it."
            );
        }
    }
}
